class TransformTests(unittest.TestCase):
    def setUp(self):
        self.clean = t.transform_bundle(bundle(), TODAY)
        self.blob = json.dumps(self.clean)

    def test_top_level_shape(self):
        self.assertEqual(set(self.clean), {"id", "ageBand", "gender", "conditions", "medications", "observations"})
        self.assertEqual((self.clean["id"], self.clean["gender"]), ("pat-1", "male"))

    def test_no_identifying_data(self):
        for leaked in ("Quintavius", "Orlando", "Zzyzxson", "Mr.", "1949", "Wallaby", "02134", "555-867",
                       "999-12-3456", "mrn-abc", "Gertrude", "Springfieldia", "Married", "Synthea"):
            self.assertNotIn(leaked, self.blob, leaked)
        for _, key in (kv for kv in t._walk(self.clean) if kv[0] == "key"):
            self.assertNotIn(key, t.FORBIDDEN_KEYS)

    def test_age_band(self):
        self.assertEqual(self.clean["ageBand"], "70-79")  # born 1949-03-15, 77 on 2026-11-07
        self.assertEqual(t.age_band("1936-11-08", TODAY), "80-89")  # day before 90th birthday
        self.assertEqual(t.age_band("1936-11-07", TODAY), "90+")
        self.assertEqual(t.age_band("2000-01-01", TODAY), "20-29")

    def test_only_active_clinical_conditions(self):
        self.assertEqual([c["display"] for c in self.clean["conditions"]],
                         ["Essential hypertension (disorder)", "Prediabetes (finding)"])

    def test_only_active_medications_and_references_resolved(self):
        self.assertEqual([m["display"] for m in self.clean["medications"]], ["Clopidogrel 75 MG", "Metformin 500 MG"])

    def test_observations_latest_per_code_bp_flattened_no_surveys(self):
        by_code = {o["code"]: o for o in self.clean["observations"]}
        self.assertEqual(set(by_code), {"8867-4", "8480-6", "8462-4", "2339-0"})
        self.assertEqual(by_code["8867-4"]["value"], 82)
        self.assertEqual((by_code["8480-6"]["value"], by_code["8462-4"]["value"]), (131, 84))
        self.assertEqual(by_code["8867-4"]["effectiveDate"], "2026-10-01")
        self.assertEqual(by_code["2339-0"]["category"], "laboratory")

    def test_deceased_patient_skipped(self):
        self.assertIsNone(t.transform_bundle(bundle(raw_patient(deceasedDateTime="2020-01-01T00:00:00Z")), TODAY))
        self.assertIsNone(t.transform_bundle(bundle(raw_patient(deceasedBoolean=True)), TODAY))

    def test_privacy_check_catches_leaks(self):
        p = raw_patient()
        with self.assertRaises(ValueError):
            t.assert_scrubbed({**self.clean, "note2": "Quintavius45 said hi"}, p)
        with self.assertRaises(ValueError):
            t.assert_scrubbed({**self.clean, "extra": {"address": "x"}}, p)
        t.assert_scrubbed(self.clean, p)  # the real output passes


class RunTests(unittest.TestCase):
    def test_writes_one_file_per_patient_and_skips_org_bundles(self):
        with tempfile.TemporaryDirectory() as tmp:
            raw, out = Path(tmp, "raw"), Path(tmp, "clean")
            raw.mkdir()
            out.mkdir()
            (out / "stale.json").write_text("{}")
            (raw / "Quintavius45_Zzyzxson123_pat-1.json").write_text(json.dumps(bundle()))
            (raw / "hospitalInformation123.json").write_text(json.dumps({"entry": []}))
            (raw / "practitionerInformation123.json").write_text(json.dumps({"entry": []}))
            cleaned = t.run(raw, out, TODAY)
            self.assertEqual([c["id"] for c in cleaned], ["pat-1"])
            self.assertEqual(sorted(p.name for p in out.iterdir()), ["pat-1.json"])  # named by id, stale removed

    def test_no_bundles_raises(self):
        with tempfile.TemporaryDirectory() as tmp, self.assertRaises(FileNotFoundError):
            t.run(Path(tmp), Path(tmp, "out"), TODAY)


@unittest.skipUnless(any(t.DEFAULT_RAW.glob("*.json")) and any(t.DEFAULT_OUT.glob("*.json")),
                     "needs data/raw and data/clean - run synthea.py and transform.py")
class RealDataTests(unittest.TestCase):
    def test_every_clean_file_is_scrubbed_against_its_raw_patient(self):
        raw_patients = {}
        for path in t.bundle_files(t.DEFAULT_RAW):
            for e in json.loads(path.read_text())["entry"]:
                if e["resource"]["resourceType"] == "Patient":
                    raw_patients[e["resource"]["id"]] = e["resource"]
        clean_files = list(t.DEFAULT_OUT.glob("*.json"))
        self.assertGreater(len(clean_files), 0)
        for path in clean_files:
            clean = json.loads(path.read_text())
            self.assertEqual(path.stem, clean["id"])
            t.assert_scrubbed(clean, raw_patients[clean["id"]])


