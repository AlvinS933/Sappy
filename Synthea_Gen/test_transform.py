def condition(code, display, status="active"):
    return {
        "resourceType": "Condition",
        "clinicalStatus": coding("http://terminology.hl7.org/CodeSystem/condition-clinical", status, status),
        "code": coding("http://snomed.info/sct", code, display),
        "subject": {"reference": PATIENT_URL},
    }


def observation(code, display, value, unit, when, category="vital-signs", components=None):
    r = {
        "resourceType": "Observation",
        "status": "final",
        "category": [coding("http://terminology.hl7.org/CodeSystem/observation-category", category, category)],
        "code": coding("http://loinc.org", code, display),
        "subject": {"reference": PATIENT_URL},
        "effectiveDateTime": when,
    }
    if value is not None:
        r["valueQuantity"] = {"value": value, "unit": unit}
    if components:
        r["component"] = components
    return r


